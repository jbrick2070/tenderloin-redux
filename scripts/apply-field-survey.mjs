#!/usr/bin/env node
// Field Guide survey importer.
//
// Reads a `tenderloin-field-survey-*.json` export from the mobile Field Photo & Surface Guide
// (tools/field-guide/, schema `tenderloin-redux.field-survey.v1`) and derives per-building
// (`sf16_bldgid`) facade color and architectural tag overrides for godot/main.gd.
//
//   node scripts/apply-field-survey.mjs [survey.json] [--apply] [--out overrides.json]
//                                       [--radius 28] [--per-stop 4] [--main godot/main.gd] [--clear]
//
// Without a path it picks the newest tenderloin-field-survey-*.json in tools/field-guide/.
// Dry run by default: prints the derived overrides. --apply rewrites only the generated
// FIELD_SURVEY_OVERRIDES block in godot/main.gd; --clear resets that block to empty.
// Photos (data URLs) and free-text notes never leave the export: only tags and colors are applied.
import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SURVEY_SCHEMA = 'tenderloin-redux.field-survey.v1';
export const BEGIN_MARKER = '# BEGIN FIELD_SURVEY_OVERRIDES';
export const END_MARKER = '# END FIELD_SURVEY_OVERRIDES';
export const BLOCK_HEADER = `${BEGIN_MARKER} (generated by scripts/apply-field-survey.mjs from a Field Guide export; edit the survey, not this block)`;
export const STOP_RADIUS_M = 28;
export const STOP_MAX_BUILDINGS = 4;

// Building-level tags understood by FIELD_SURVEY_TAG_STYLES in godot/main.gd (same order).
export const BUILDING_TAGS = [
  'Red Brick', 'Buff/Tan Brick', 'Cream Stucco', 'Sage/Teal Paint', 'Terracotta Ornate Trim',
  'Angled Bay Windows', 'Rounded Bay Windows', 'Sloped Fabric Awning', 'Flat Metal Marquee',
  'Vertical Neon Blade Sign', 'Iron Fire Escape', 'Arched Mezzanine Windows', 'Painted Wall Mural',
  'Rooftop Water Tank', 'Elevator Penthouse', 'Skylights'
];
// Street-level tags describe the sidewalk/roadway, not a building, so they are reported but not applied.
export const STREET_TAGS = ['Green Bike Lane', 'Continental Crosswalk', 'Sidewalk Trees / Planters'];
const COLOR_FIELDS = { facade: 'base', trim: 'cornice' };

const repoRoot = fileURLToPath(new URL('../', import.meta.url));

export function normalizeHex(value) {
  if (typeof value !== 'string') return null;
  const m = value.trim().match(/^#?([0-9a-fA-F]{6})$/);
  return m ? `#${m[1].toLowerCase()}` : null;
}

export function validateSurvey(survey) {
  const errors = [];
  if (!survey || typeof survey !== 'object' || Array.isArray(survey)) {
    errors.push('survey must be a JSON object');
    return errors;
  }
  if (survey.schema !== SURVEY_SCHEMA) errors.push(`schema must be "${SURVEY_SCHEMA}" (got ${JSON.stringify(survey.schema)})`);
  if (survey.stops !== undefined && !Array.isArray(survey.stops)) errors.push('stops must be an array');
  if (survey.buildings !== undefined && (typeof survey.buildings !== 'object' || survey.buildings === null || Array.isArray(survey.buildings))) {
    errors.push('buildings must be an object keyed by sf16_bldgid');
  }
  return errors;
}

function segmentDistance(px, pz, ax, az, bx, bz) {
  const dx = bx - ax, dz = bz - az;
  const len2 = dx * dx + dz * dz;
  const t = len2 < 1e-12 ? 0 : Math.max(0, Math.min(1, ((px - ax) * dx + (pz - az) * dz) / len2));
  return Math.hypot(px - (ax + dx * t), pz - (az + dz * t));
}

function pointInRing(x, z, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, zi] = ring[i];
    const [xj, zj] = ring[j];
    if ((zi > z) !== (zj > z) && x < ((xj - xi) * (z - zi)) / (zj - zi || 1e-12) + xi) inside = !inside;
  }
  return inside;
}

/** Metres from a game-space point to a footprint (0 when inside its outer ring). */
export function footprintDistance(x, z, building) {
  let best = Infinity;
  for (const poly of building.polygons || []) {
    const ring = poly.rings && poly.rings[0];
    if (!ring || ring.length < 3) continue;
    if (pointInRing(x, z, ring)) return 0;
    for (let i = 0; i < ring.length; i++) {
      const [ax, az] = ring[i];
      const [bx, bz] = ring[(i + 1) % ring.length];
      best = Math.min(best, segmentDistance(x, z, ax, az, bx, bz));
    }
  }
  return best;
}

function orderedTags(tags) {
  const set = new Set(tags);
  return BUILDING_TAGS.filter(t => set.has(t));
}

/**
 * Derive overrides from a survey export and the city footprints in godot/data/buildings.json.
 * Stop tags propagate to the nearest footprints within `radius` metres of the stop (at most
 * `perStop`); per-building records from the Field Guide inspector add tags and colors and win
 * on conflicts. Unknown building ids, unknown tags, photos, and notes are reported, never applied.
 */
export function deriveOverrides(survey, cityData, { radius = STOP_RADIUS_M, perStop = STOP_MAX_BUILDINGS } = {}) {
  const errors = validateSurvey(survey);
  if (errors.length) throw new Error(`Invalid field survey: ${errors.join('; ')}`);
  const buildings = [...(cityData.buildings || []), ...(cityData.wider_buildings || [])];
  const byId = new Map(buildings.map(b => [String(b.id), b]));
  const report = { stopsWithTags: 0, stopMatches: {}, unknownIds: [], unknownTags: [], streetTags: [], photosIgnored: 0, notesIgnored: 0, invalidColors: [] };
  const work = new Map();
  const entry = id => {
    if (!work.has(id)) work.set(id, { tags: new Set(), colors: {}, sources: new Set() });
    return work.get(id);
  };
  const noteTag = tag => {
    if (STREET_TAGS.includes(tag)) { if (!report.streetTags.includes(tag)) report.streetTags.push(tag); }
    else if (!report.unknownTags.includes(tag)) report.unknownTags.push(tag);
  };

  for (const stop of survey.stops || []) {
    const rec = stop && stop.survey;
    if (!rec) continue;
    report.photosIgnored += Array.isArray(rec.photos) ? rec.photos.length : 0;
    if (typeof rec.notes === 'string' && rec.notes.trim()) report.notesIgnored += 1;
    const tags = (Array.isArray(rec.tags) ? rec.tags : []).filter(t => typeof t === 'string');
    const applicable = tags.filter(t => BUILDING_TAGS.includes(t));
    tags.filter(t => !BUILDING_TAGS.includes(t)).forEach(noteTag);
    if (!applicable.length || !Number.isFinite(stop.x) || !Number.isFinite(stop.z)) continue;
    report.stopsWithTags += 1;
    const near = buildings
      .map(b => ({ id: String(b.id), d: footprintDistance(stop.x, stop.z, b) }))
      .filter(c => c.d <= radius)
      .sort((a, b) => a.d - b.d || a.id.localeCompare(b.id))
      .slice(0, perStop);
    report.stopMatches[String(stop.id)] = near.map(c => c.id);
    for (const c of near) {
      const e = entry(c.id);
      applicable.forEach(t => e.tags.add(t));
      e.sources.add(`stop:${stop.id}`);
    }
  }

  for (const [rawId, rec] of Object.entries(survey.buildings || {})) {
    const id = String(rawId);
    if (!rec || typeof rec !== 'object') continue;
    report.photosIgnored += Array.isArray(rec.photos) ? rec.photos.length : 0;
    if (typeof rec.notes === 'string' && rec.notes.trim()) report.notesIgnored += 1;
    const tags = (Array.isArray(rec.tags) ? rec.tags : []).filter(t => typeof t === 'string');
    const colors = {};
    for (const [field, target] of Object.entries(COLOR_FIELDS)) {
      if (rec[field] === undefined || rec[field] === null || rec[field] === '') continue;
      const hex = normalizeHex(rec[field]);
      if (hex) colors[target] = hex;
      else report.invalidColors.push(`${id}.${field}`);
    }
    const applicable = tags.filter(t => BUILDING_TAGS.includes(t));
    tags.filter(t => !BUILDING_TAGS.includes(t)).forEach(noteTag);
    if (!applicable.length && !Object.keys(colors).length) continue;
    if (!byId.has(id)) { report.unknownIds.push(id); continue; }
    const e = entry(id);
    applicable.forEach(t => e.tags.add(t));
    Object.assign(e.colors, colors);
    e.sources.add('building');
  }

  const overrides = {};
  for (const id of [...work.keys()].sort()) {
    const e = work.get(id);
    const out = { tags: orderedTags([...e.tags]) };
    if (e.colors.base) out.base = e.colors.base;
    if (e.colors.cornice) out.cornice = e.colors.cornice;
    out.source = e.sources.has('building')
      ? (e.sources.size > 1 ? 'building+stop' : 'building')
      : [...e.sources].sort()[0];
    overrides[id] = out;
  }
  return { overrides, report };
}

function gdString(value) {
  // JSON string escapes (\" \\ \n \uXXXX) are valid GDScript string escapes.
  return JSON.stringify(String(value));
}

export function sourceLabel(fileName, survey, count) {
  const safeName = path.basename(String(fileName || 'field-survey.json')).replace(/[^A-Za-z0-9._-]/g, '_');
  const when = typeof survey.exportedAt === 'string' ? survey.exportedAt.replace(/[^0-9TZ:.-]/g, '') : 'unknown';
  return `${safeName} | exported ${when} | ${count} building${count === 1 ? '' : 's'}`;
}

/** GDScript block between (and including) the BEGIN/END markers. */
export function renderGdBlock(overrides, label = '') {
  const lines = [BLOCK_HEADER, `const FIELD_SURVEY_SOURCE := ${gdString(label)}`];
  const ids = Object.keys(overrides).sort();
  if (!ids.length) {
    lines.push('const FIELD_SURVEY_OVERRIDES: Dictionary = {}');
  } else {
    lines.push('const FIELD_SURVEY_OVERRIDES: Dictionary = {');
    ids.forEach((id, idx) => {
      const o = overrides[id];
      const parts = [`"tags": [${o.tags.map(gdString).join(', ')}]`];
      if (o.base) parts.push(`"base": ${gdString(o.base)}`);
      if (o.cornice) parts.push(`"cornice": ${gdString(o.cornice)}`);
      parts.push(`"source": ${gdString(o.source)}`);
      lines.push(`\t${gdString(id)}: {${parts.join(', ')}}${idx < ids.length - 1 ? ',' : ''}`);
    });
    lines.push('}');
  }
  lines.push(END_MARKER);
  return lines.join('\n');
}

/** Replace the generated block in main.gd source; throws if the markers are missing or duplicated. */
export function applyBlock(source, block) {
  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  const start = source.indexOf(BEGIN_MARKER);
  const endAt = source.indexOf(END_MARKER);
  if (start < 0 || endAt < 0 || endAt < start) throw new Error('godot/main.gd is missing the FIELD_SURVEY_OVERRIDES markers');
  if (source.indexOf(BEGIN_MARKER, start + 1) >= 0 || source.indexOf(END_MARKER, endAt + 1) >= 0) throw new Error('godot/main.gd has duplicate FIELD_SURVEY_OVERRIDES markers');
  const end = endAt + END_MARKER.length;
  return source.slice(0, start) + block.split('\n').join(eol) + source.slice(end);
}

export async function findLatestSurvey(dir) {
  let names = [];
  try {
    names = (await readdir(dir)).filter(n => /^tenderloin-field-survey-.*\.json$/i.test(n));
  } catch {
    return null;
  }
  if (!names.length) return null;
  const withTimes = await Promise.all(names.map(async n => ({ n, t: (await stat(path.join(dir, n))).mtimeMs })));
  withTimes.sort((a, b) => b.n.localeCompare(a.n) || b.t - a.t);
  return path.join(dir, withTimes[0].n);
}

function parseArgs(argv) {
  const opts = { apply: false, clear: false, out: null, radius: STOP_RADIUS_M, perStop: STOP_MAX_BUILDINGS, main: path.join(repoRoot, 'godot/main.gd'), file: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--apply') opts.apply = true;
    else if (a === '--clear') opts.clear = true;
    else if (a === '--out') opts.out = argv[++i];
    else if (a === '--radius') opts.radius = Number(argv[++i]);
    else if (a === '--per-stop') opts.perStop = Number(argv[++i]);
    else if (a === '--main') opts.main = argv[++i];
    else if (a === '--help' || a === '-h') opts.help = true;
    else if (a.startsWith('--')) throw new Error(`Unknown option ${a}`);
    else opts.file = a;
  }
  if (!Number.isFinite(opts.radius) || opts.radius <= 0) throw new Error('--radius must be a positive number of metres');
  if (!Number.isInteger(opts.perStop) || opts.perStop < 1) throw new Error('--per-stop must be a positive integer');
  return opts;
}

async function main(argv) {
  const opts = parseArgs(argv);
  if (opts.help) {
    console.log('Usage: node scripts/apply-field-survey.mjs [survey.json] [--apply] [--clear] [--out overrides.json] [--radius 28] [--per-stop 4] [--main godot/main.gd]');
    return;
  }
  if (opts.clear) {
    const src = await readFile(opts.main, 'utf8');
    await writeFile(opts.main, applyBlock(src, renderGdBlock({}, '')));
    console.log(`Cleared FIELD_SURVEY_OVERRIDES in ${path.relative(repoRoot, opts.main)}. Run npm run godot:test && npm run godot:export to rebuild.`);
    return;
  }
  const file = opts.file || await findLatestSurvey(path.join(repoRoot, 'tools/field-guide'));
  if (!file) throw new Error('No survey given and no tools/field-guide/tenderloin-field-survey-*.json found. Export one from the Field Guide first.');
  const survey = JSON.parse(await readFile(file, 'utf8'));
  const cityData = JSON.parse(await readFile(path.join(repoRoot, 'godot/data/buildings.json'), 'utf8'));
  const { overrides, report } = deriveOverrides(survey, cityData, { radius: opts.radius, perStop: opts.perStop });
  const count = Object.keys(overrides).length;
  const label = sourceLabel(file, survey, count);
  console.log(`Field survey: ${path.relative(process.cwd(), file)}`);
  console.log(`  ${count} building override(s) from ${report.stopsWithTags} tagged stop(s) and the building inspector`);
  for (const [id, o] of Object.entries(overrides)) {
    const colors = [o.base && `facade ${o.base}`, o.cornice && `trim ${o.cornice}`].filter(Boolean).join(', ');
    console.log(`  ${id}  [${o.source}]  ${o.tags.join(', ') || '(no tags)'}${colors ? `  ${colors}` : ''}`);
  }
  if (report.unknownIds.length) console.log(`  Skipped unknown building ids: ${report.unknownIds.join(', ')}`);
  if (report.unknownTags.length) console.log(`  Skipped unknown tags: ${report.unknownTags.join(', ')}`);
  if (report.streetTags.length) console.log(`  Street-level tags noted (not building overrides): ${report.streetTags.join(', ')}`);
  if (report.invalidColors.length) console.log(`  Skipped invalid colors: ${report.invalidColors.join(', ')}`);
  console.log(`  Not applied by design: ${report.photosIgnored} photo(s), ${report.notesIgnored} note(s)`);
  if (opts.out) {
    await writeFile(opts.out, JSON.stringify({ schema: 'tenderloin-redux.field-survey-overrides.v1', source: label, overrides, report }, null, 2) + '\n');
    console.log(`  Wrote ${opts.out}`);
  }
  if (opts.apply) {
    const src = await readFile(opts.main, 'utf8');
    const next = applyBlock(src, renderGdBlock(overrides, label));
    if (next === src) console.log(`  ${path.relative(repoRoot, opts.main)} already up to date`);
    else {
      await writeFile(opts.main, next);
      console.log(`  Applied to ${path.relative(repoRoot, opts.main)}. Run npm run godot:test && npm run godot:export to rebuild.`);
    }
  } else {
    console.log('  Dry run: pass --apply to write godot/main.gd');
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch(err => {
    console.error(err.message);
    process.exitCode = 1;
  });
}
